#!/usr/bin/env node
// npm run content:status — rewrites the unit table of content/STATUS.md from the facts:
// generated = the pack file equals what the sources generate; reviewed = content/review/<track>/<unit>.md has an
// author's resolution; audio = every clip of the unit (vocabulary + sentences, normal + slow) is in audio/manifest.json.
import fs from 'node:fs';
import path from 'node:path';
import { generatorOptions, readPackSources, ROOT, SRC_DIR, withAppended } from './sources.js';
import { generatePack } from './generator.js';
import { formatPack } from '../format-packs.js';
import { normalizeText } from '../../server/src/audio/clips.js';

const STATUS = path.join(ROOT, 'content/STATUS.md');
// content/review/ (the review files) and STATUS.md are working papers kept with the installation that authors lessons, not
// in the repository: without the folder every unit counts as not reviewed, and the run says so.
const REVIEWS = path.join(ROOT, 'content/review');
if (!fs.existsSync(REVIEWS)) {
  console.log('content/review/ is not here (the review files are local working papers, not in the repository): the Reviewed column says — for every unit.');
}
const manifest = (() => {
  try {
    return JSON.parse(fs.readFileSync(path.join(ROOT, 'audio/manifest.json'), 'utf8'));
  } catch {
    return { clips: {} };
  }
})();
const rows = [];
for (const track of fs.readdirSync(SRC_DIR).filter((d) => fs.statSync(path.join(SRC_DIR, d)).isDirectory())) {
  const levels = fs.readdirSync(path.join(SRC_DIR, track)).filter((d) => fs.existsSync(path.join(SRC_DIR, track, d, 'pack.yaml')));
  const order = ['pre-a1', 'a1-1', 'a1', 'a2'];
  for (const level of levels.sort((a, b) => order.indexOf(a) - order.indexOf(b))) {
    const packId = `${track}-${level}`;
    const { meta, units: sourceUnits } = readPackSources(packId);
    const units = sourceUnits.map(withAppended);
    const packFile = path.join(ROOT, 'content/packs', track, `${level}.json`);
    const generated = fs.existsSync(packFile) && fs.readFileSync(packFile, 'utf8') === formatPack(generatePack({ track, ...meta }, sourceUnits, generatorOptions(packId)));
    const clips = manifest.clips?.[track] ?? {};
    for (const u of units) {
      // the unit's review, and for appended content (unit append:) its own review <unit>-append.md, both resolved
      const isResolved = (file) => fs.existsSync(file) && /## Author's resolution\s*\n\s*\n?\s*[-*|A-Za-z0-9]/.test(fs.readFileSync(file, 'utf8'))
        && !/\(left empty for the author\)/.test(fs.readFileSync(file, 'utf8'));
      const reviewFile = (suffix = '') => path.join(REVIEWS, track, `${u.id}${suffix}.md`);
      const resolved = isResolved(reviewFile()) && (!u.append?.length || isResolved(reviewFile('-append')));
      const texts = [...u.vocabulary.map((v) => v.target), ...(u.sentences || []).map((s) => s.target)].map(normalizeText);
      const audio = texts.every((t) => clips.normal?.[t] && clips.slow?.[t] && fs.existsSync(path.join(ROOT, 'audio', clips.normal[t])));
      const yes = (b) => (b ? 'yes' : '—');
      rows.push(`| ${u.id} | ${meta.cefr} | ${Object.values(u.title)[0]} | ${u.topic ?? ''} | ${u.vocabulary.length} | ${(u.sentences || []).length} | ${yes(generated)} | ${yes(resolved)} | ${yes(audio)} | ${generated && resolved && audio ? 'done' : '—'} |`);
    }
  }
}
const head = fs.existsSync(STATUS) ? fs.readFileSync(STATUS, 'utf8').split('\n## Units')[0].trimEnd() : '# Content status';
const table = ['## Units', '', 'Generated by `npm run content:status` (do not edit the table by hand).', '',
  '| Unit | Level | Title | Topic | Vocab | Sentences | Generated | Reviewed | Audio | Done |', '|---|---|---|---|---|---|---|---|---|---|', ...rows];
fs.writeFileSync(STATUS, `${head}\n\n${table.join('\n')}\n`);
console.log(`content/STATUS.md: ${rows.length} units, ${rows.filter((r) => r.endsWith('| done |')).length} done`);
